#!/usr/bin/env node
/**
 * 在 tsup 跑完之后写 dist/theme/index.d.ts + .d.cts。
 *
 * 为什么不放 tsup.config.ts 的 onSuccess?
 *   onSuccess 在 ESM/CJS build 之后、DTS build 之前触发。tsup 的 DTS 步骤会
 *   重整 dist 目录(具体机制不明,实测会清掉 dist/theme/ 下我们手写的文件)。
 *   所以放到 `tsup && node scripts/write-theme-dts.mjs` 链路里、tsup 全完
 *   之后再写,可靠。
 */

import { mkdirSync, writeFileSync } from 'node:fs'

const content = `// AUTO-GENERATED by scripts/write-theme-dts.mjs —— do not edit
import type { Theme } from 'vitepress'
import type { DefineComponent, Ref } from 'vue'

export interface VaultData {
  nodes: VaultDataNode[]
  edges: VaultDataEdge[]
  tags: Record<string, VaultDataTagInfo>
  stats: VaultDataStats
  meta: { generatedAt: number; pluginVersion: string }
}

export interface VaultDataNode {
  id: string
  title: string
  url: string
  tags: string[]
  mtime: number
}

export interface VaultDataEdge {
  source: string
  target: string
  type: 'wikilink' | 'transclusion'
}

export interface VaultDataTagInfo {
  count: number
  files: {
    id: string
    url: string
    title: string
    mtime: number
    path: string
    otherTags: string[]
  }[]
}

export interface VaultDataStats {
  totalFiles: number
  totalAssets: number
  totalWikilinks: number
  totalTags: number
  totalWarnings: number
  mostRecent: { id: string; url: string; title: string; mtime: number }[]
}

export interface UseVaultDataResult {
  data: Ref<VaultData | null>
  loading: Ref<boolean>
  error: Ref<string | null>
  reload: () => Promise<void>
}

export declare function useVaultData(fileName?: string): UseVaultDataResult

export declare const VaultGraph: DefineComponent<{ maxNodes?: number }>
export declare const VaultStats: DefineComponent<Record<string, never>>
export declare const Tags: DefineComponent<Record<string, never>>
export declare const Layout: DefineComponent<Record<string, never>>
export declare const DocHeader: DefineComponent<Record<string, never>>

/**
 * v0.5: 主题工厂。传 \`{}\` / 不传 → 默认 preset(等同 \`export default theme\`)。
 * 传 \`Layout\` / \`extends\` / \`enhanceApp\` / \`setup\` 任意子集,覆盖默认。
 *
 * 用法举例见 src/theme/index.ts 文件头注释。
 */
export declare function defineTheme(userTheme?: Partial<Theme>): Theme

declare const theme: Theme
export default theme
`

mkdirSync('dist/theme', { recursive: true })
writeFileSync('dist/theme/index.d.ts', content, 'utf8')
writeFileSync('dist/theme/index.d.cts', content, 'utf8')
// eslint-disable-next-line no-console
console.log('  ✓ dist/theme/index.d.ts + .d.cts (hand-crafted, post-tsup)')
